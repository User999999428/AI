"""FocusEye+ 설정값 모음.

사람마다 눈 크기, 카메라 위치, 조명이 달라서 알맞은 기준값도 다르다.
잘 맞지 않으면 이 파일의 숫자만 바꾸면 된다. (코드는 고칠 필요 없음)

기준값을 바꾸는 방법 3가지 (쉬운 순서)
  1. 실행 중에 c 키 → 3초 동안 눈을 편하게 뜨고 화면을 보면 내 눈에 맞게 자동 설정 (이번 실행에만 적용)
  2. 실행할 때 옵션으로 주기 (이번 실행에만 적용)
        python main.py --ear-threshold 0.2 --drowsy-seconds 2
  3. 아래 숫자를 직접 고치기 (항상 적용)
     → 1번에서 나온 값이 잘 맞으면 여기에 적어 두면 된다.
"""

# ── 2단계: 눈 감김 감지 ──────────────────────────────────────

# 눈 감김 기준값 (EAR)
#   EAR = 눈이 얼마나 떠 있는지 나타내는 숫자. 클수록 크게 뜬 것.
#   눈을 감으면 대부분 0.1 아래로 떨어진다.
#     (CEW 데이터셋 눈 감은 사진 1172장: 중앙값 0.05, 가끔 0.25까지)
#   눈을 뜬 값은 사람·표정마다 크게 달라서 테스트 사진에서도 0.20~0.55까지 나왔다.
#   (특히 활짝 웃으면 눈이 가늘어져 0.20 근처까지 내려간다)
#   EAR이 이 값보다 작으면 '눈을 감았다'고 판단한다.
#
#   [0.18로 정한 근거] (자세한 내용: docs/stage2_eye_closure.md 7절)
#     - CEW 눈 감은 사진의 98.5%를 '감음'으로 맞힌다. (0.10이면 83.9%로 많이 놓침)
#     - 웃을 때 눈 뜬 EAR(약 0.20)보다는 낮아서, 뜬 눈을 감았다고 잘못 볼 위험을 줄인다.
#     - 단, 눈 뜬 사진은 3장으로만 확인했다. 눈 뜬 사진 데이터가 생기면 다시 검증할 것.
#     - 눈을 떴는데도 CLOSED가 자주 뜨면  → 값을 낮춘다
#     - 눈을 감았는데도 OPEN으로 나오면     → 값을 높인다
EAR_THRESHOLD = 0.18

# 졸음 판단 시간 (초)
#   눈을 이 시간 이상 '계속' 감고 있으면 졸음 경고를 띄운다.
#   보통 눈 깜빡임은 0.1~0.4초라서, 이보다 충분히 길게 잡아야 깜빡임을 졸음으로 착각하지 않는다.
DROWSY_SECONDS = 1.5

# EAR 흔들림 줄이기 (0~1)
#   매 프레임 EAR 값이 조금씩 떨려서 숫자가 깜빡거리는 것을 줄인다.
#   새 값을 얼마나 반영할지 비율이다. 1이면 그대로, 작을수록 부드럽지만 반응이 느려진다.
EAR_SMOOTHING = 0.5

# 보정(c 키) 설정
#   보정하는 동안 '눈 뜬 EAR'을 모아서, 그 값에 아래 비율을 곱한 것을 기준값으로 정한다.
#   예) 눈 뜬 EAR이 0.30이면 0.30 × 0.6 = 0.18 이 기준값이 된다.
#   (눈을 반쯤 감았을 때를 '감음'으로 보는 정도. 너무 민감하면 비율을 낮춘다)
CALIBRATION_SECONDS = 3.0
CALIBRATION_RATIO = 0.6
